import esbuild from "esbuild";
import process from "process";
import { cpSync, mkdirSync, rmSync, writeFileSync, existsSync } from "node:fs";
import { get } from "node:https";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Source files are in the "src" directory.
*/
`;

const prod = (process.argv[2] === "production");

const STATIC_ASSETS = ["manifest.json", "styles.css"];

const ACCENTS_URL =
	"https://raw.githubusercontent.com/mifunetoshiro/kanjium/master/data/source_files/raw/accents.txt";
const ACCENTS_PATH = "dist/accents.txt";

function syncStaticAssets() {
	mkdirSync("dist", { recursive: true });
	for (const name of STATIC_ASSETS) {
		cpSync(name, `dist/${name}`);
	}
}

/** 下载 kanjium accents.txt 到 dist/accents.txt（已存在则跳过，离线可手动放入） */
function downloadAccents() {
	return new Promise((resolve) => {
		if (existsSync(ACCENTS_PATH)) {
			console.log(`[build] ${ACCENTS_PATH} 已存在，跳过下载`);
			resolve();
			return;
		}
		const req = get(ACCENTS_URL, (res) => {
			if (res.statusCode !== 200) {
				console.warn(
					`[build] 下载 accents.txt 失败: HTTP ${res.statusCode}（可手动放入 dist/accents.txt）`,
				);
				resolve();
				return;
			}
			const chunks = [];
			res.on("data", (c) => chunks.push(c));
			res.on("end", () => {
				writeFileSync(ACCENTS_PATH, Buffer.concat(chunks));
				console.log(`[build] 已下载 accents.txt -> ${ACCENTS_PATH}`);
				resolve();
			});
		});
		req.on("error", (e) => {
			console.warn(`[build] 下载 accents.txt 出错: ${e.message}（可手动放入 dist/accents.txt）`);
			resolve();
		});
		req.end();
	});
}

function cleanDist() {
	rmSync("dist", { recursive: true, force: true });
}

if (prod) {
	cleanDist();
}

const context = await esbuild.context({
	entryPoints: ["src/main.ts"],
	banner: { js: banner },
	target: "es2018",
	platform: "browser",
	format: "cjs",
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
	],
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outdir: "dist",
	minify: prod
});

if (prod) {
	await context.rebuild();
	syncStaticAssets();
	await downloadAccents();
	process.exit(0);
} else {
	syncStaticAssets();
	await context.watch();
}
